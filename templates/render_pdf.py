#!/usr/bin/env python3
"""Deterministic Markdown -> HTML/CSS -> PDF renderer (WeasyPrint).

Replaces the old LaTeX/xelatex path and the per-run improvised fpdf2 scripts
with ONE committed renderer. Produces a branded, chart-embedded, bilingual PDF
from the final markdown report plus the pipeline's JSON artifacts.

Usage:
    .venv/bin/python3 templates/render_pdf.py <workspace> <date>

Inputs (under {workspace}):
    final/{date}/{daily_report|weekly_report}.md   — the report body
    decision/{date}/final_decision.json            — rating box
    quant/{date}/quant_summary.json                — price + key metrics
    valuation/{date}/valuation_summary.json        — fair value / margin of safety
    profile/company_profile.json                   — company meta + market cap
    exports/{date}/pdf/charts/*.svg                — charts (from charts.py)
    resolved_config.json                           — language + run_mode

Output:
    exports/{date}/pdf/report.pdf   (and report.html for debugging)

Never crashes the (non-critical) export stage: missing artifacts degrade
gracefully to "—" / omitted sections.
"""

